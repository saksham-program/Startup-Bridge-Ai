#!/usr/bin/env node
/**
 * Generates src/lib/demo/seed.generated.ts from the SQL demo seed files, so Local Demo Mode and
 * the Supabase demo seed always describe the same data.
 *
 *   node scripts/generate-demo-seed.mjs
 *
 * It understands only the literal forms used by the seed files (strings, numbers, booleans, NULL,
 * `x::type` casts, '{a,b}' arrays, JSON text, `now() - interval 'N days'`, `current_date +/- N`).
 * Anything else throws, so a future seed change cannot be silently mis-parsed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ARRAY_COLS = new Set(["tags", "skills", "industry_interests", "investment_interests", "preferred_industries", "preferred_stages", "interests"]);
const JSON_COLS = new Set(["team", "target_audience", "options", "answers", "result", "metadata", "notification_prefs"]);
const UNIT_MS = { minute: 60e3, hour: 3600e3, day: 86400e3, week: 7 * 86400e3 };

function parseTuples(text, startIdx, columns) {
  const rows = [];
  let i = startIdx;
  const ws = () => { while (i < text.length && /[\s]/.test(text[i])) i++; };
  const skipComments = () => { for (;;) { ws(); if (text.startsWith("--", i)) { while (i < text.length && text[i] !== "\n") i++; } else break; } };
  const readValue = (col) => {
    skipComments();
    let v;
    if (text[i] === "'") {
      let s = ""; i++;
      for (;;) {
        if (text[i] === "'" && text[i + 1] === "'") { s += "'"; i += 2; }
        else if (text[i] === "'") { i++; break; }
        else s += text[i++];
      }
      v = s;
      if (ARRAY_COLS.has(col) && s.startsWith("{")) v = s.slice(1, -1) === "" ? [] : s.slice(1, -1).split(",").map((x) => x.replace(/^"|"$/g, ""));
      else if (JSON_COLS.has(col)) v = JSON.parse(s);
    } else {
      const m = /^(null|true|false|-?\d+(?:\.\d+)?|now\(\)|current_date)/i.exec(text.slice(i, i + 20));
      if (!m) throw new Error(`Cannot parse value for ${col} near: ${text.slice(i, i + 60)}`);
      i += m[0].length;
      const tok = m[0].toLowerCase();
      if (tok === "null") v = null;
      else if (tok === "true") v = true;
      else if (tok === "false") v = false;
      else if (tok === "now()" || tok === "current_date") {
        const rest = /^\s*([+-])\s*(?:interval\s*'(\d+)\s*(minute|hour|day|week)s?'|(\d+))/i.exec(text.slice(i, i + 60));
        let sign = 0, qty = 0, unit = "day";
        if (rest) {
          i += rest[0].length; sign = rest[1] === "-" ? -1 : 1;
          qty = Number(rest[2] ?? rest[4]); unit = (rest[3] ?? "day").toLowerCase();
        }
        v = tok === "now()" ? { $offsetMs: sign * qty * UNIT_MS[unit] } : { $todayPlusDays: sign * qty };
      } else v = Number(tok);
    }
    const cast = /^::[a-z_]+/i.exec(text.slice(i, i + 20));
    if (cast) i += cast[0].length;
    return v;
  };
  for (;;) {
    skipComments();
    if (text[i] !== "(") break;
    i++;
    const row = {};
    for (let c = 0; c < columns.length; c++) {
      row[columns[c]] = readValue(columns[c]);
      skipComments();
      if (text[i] === ",") i++;
    }
    skipComments();
    if (text[i] !== ")") throw new Error(`Expected ) near: ${text.slice(i, i + 60)}`);
    i++;
    rows.push(row);
    skipComments();
    if (text[i] === ",") { i++; continue; }
    break;
  }
  return rows;
}

const out = [];

// 1. Base seed: plain `insert into public.<table> (cols) values (...), (...);`
const base = readFileSync(resolve(root, "scripts/seed-demo-data.sql"), "utf8");
for (const m of base.matchAll(/insert into public\.(\w+)\s*\(([^)]*)\)\s*values/gi)) {
  const columns = m[2].split(",").map((c) => c.trim());
  const rows = parseTuples(base, m.index + m[0].length, columns);
  out.push({ table: m[1], rows });
}

// 2. Optional startups: `FROM (VALUES (...), (...)) AS demo (cols)`; is_public is always true.
const opt = readFileSync(resolve(root, "scripts/seed-demo-startups.sql"), "utf8");
const vm = /FROM \(VALUES/i.exec(opt);
const am = /\)\s*AS demo \(([^)]*)\)/i.exec(opt);
if (vm && am) {
  const columns = am[1].split(",").map((c) => c.trim());
  const rows = parseTuples(opt, vm.index + vm[0].length, columns).map((r) => ({ ...r, is_public: true }));
  out.push({ table: "startups", rows });
}

const header = `// AUTO-GENERATED by scripts/generate-demo-seed.mjs from scripts/seed-demo-data.sql and
// scripts/seed-demo-startups.sql. Do not edit by hand; re-run \`bun run demo:generate\`.
// Used ONLY by Local Demo Mode. Time values are relative to the moment the demo store is created.
export type SeedTime = { $offsetMs: number } | { $todayPlusDays: number };
export type SeedValue = string | number | boolean | null | SeedTime | SeedValue[] | { [k: string]: SeedValue };
export type SeedTable = { table: string; rows: Record<string, SeedValue>[] };

export const DEMO_SEED: SeedTable[] = `;
writeFileSync(resolve(root, "src/lib/demo/seed.generated.ts"), header + JSON.stringify(out, null, 1) + ";\n");
console.log(out.map((t) => `${t.table}: ${t.rows.length}`).join("\n"));
